impl Tree {
    /// Initialise an empty tree (called once from `init_pool`).
    pub fn init(&mut self, pool: Pubkey) {
        self.pool = pool;
        self.next_index = 0;
        self.current_root_index = 0;
        self.filled_subtrees.copy_from_slice(&ZEROS[..DEPTH]);
        self.roots = [[0u8; 32]; ROOT_HISTORY];
        self.roots[0] = ZEROS[DEPTH];
    }

    /// The most recent root.
    pub fn root(&self) -> [u8; 32] {
        self.roots[self.current_root_index as usize]
    }

    /// `root` is one of the last 128 roots. 0 (an unused slot) is never known.
    pub fn is_known_root(&self, root: &[u8; 32]) -> bool {
        *root != [0u8; 32] && self.roots.iter().any(|r| r == root)
    }

    /// Append the two output commitments of an action at `next_index`
    /// (always even). Costs 26 `sol_poseidon` calls: H_2(cm0, cm1), then one
    /// per level 1..26. Returns the leaf index of `cm0` (`cm1` is at +1).
    pub fn append_pair(&mut self, cm0: &[u8; 32], cm1: &[u8; 32]) -> Result<u64> {
        let first = self.next_index;
        require!(first % 2 == 0, PoolError::TreeCorrupted);
        require!(first + 2 <= CAPACITY, PoolError::TreeFull);

        let mut cur = poseidon(&[cm0, cm1])?;
        // Index of `cur` within level 1.
        let mut idx = first >> 1;
        for level in 1..DEPTH {
            cur = if idx & 1 == 0 {
                // `cur` is a left child: remember it, its right sibling is empty.
                self.filled_subtrees[level] = cur;
                poseidon(&[&cur, &ZEROS[level]])?
            } else {
                poseidon(&[&self.filled_subtrees[level], &cur])?
            };
            idx >>= 1;
        }

        self.next_index = first + 2;
        self.current_root_index = (self.current_root_index + 1) % ROOT_HISTORY as u64;
        self.roots[self.current_root_index as usize] = cur;
        Ok(first)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use polypus_crypto::{
        field::{from_u64, to_bytes_be, Fr},
        merkle::{self, Frontier, MerkleTree},
    };

    fn empty_tree() -> Box<Tree> {
        let mut t: Box<Tree> = Box::new(bytemuck::Zeroable::zeroed());
        t.init(Pubkey::default());
        t
    }

    fn be(x: &Fr) -> [u8; 32] {
        to_bytes_be(x)
    }

    #[test]
    fn zero_hashes() {
        // Against solana-poseidon (the host build of the syscall) ...
        let mut z = [0u8; 32];
        for (i, zi) in ZEROS.iter().enumerate() {
            assert_eq!(*zi, z, "Z_{i}");
            z = solana_poseidon::hashv(
                solana_poseidon::Parameters::Bn254X5,
                solana_poseidon::Endianness::BigEndian,
                &[&z, &z],
            )
            .unwrap()
            .to_bytes();
        }
        // ... and against the reference implementation.
        for (i, zi) in merkle::zeros().iter().enumerate() {
            assert_eq!(ZEROS[i], be(zi), "Z_{i} vs polypus-crypto");
        }
        assert_eq!(merkle::DEPTH, DEPTH);
        assert_eq!(merkle::ROOT_HISTORY, ROOT_HISTORY);
    }

    #[test]
    fn append_parity_with_reference() {
        let mut t = empty_tree();
        let mut full = MerkleTree::new();
        let mut frontier = Frontier::default();
        assert_eq!(t.root(), be(&full.root()));
        for i in 0..40u64 {
            let (a, b) = (from_u64(7 * i + 1), from_u64(7 * i + 2));
            assert_eq!(t.append_pair(&be(&a), &be(&b)).unwrap(), 2 * i);
            full.append(a).unwrap();
            full.append(b).unwrap();
            frontier.append_pair(a, b).unwrap();
            assert_eq!(t.root(), be(&full.root()), "root after pair {i}");
            assert_eq!(t.root(), be(&frontier.root()));
            for l in 1..DEPTH {
                assert_eq!(t.filled_subtrees[l], be(&frontier.filled_subtrees[l]));
            }
        }
        assert_eq!(t.next_index, 80);
    }

    #[test]
    fn root_history_ring() {
        let mut t = empty_tree();
        let empty = t.root();
        assert_eq!(empty, ZEROS[DEPTH]);
        assert!(t.is_known_root(&empty));
        assert!(!t.is_known_root(&[0u8; 32]));
        let mut roots = vec![empty];
        for i in 0..ROOT_HISTORY as u64 {
            t.append_pair(&be(&from_u64(i + 1)), &be(&from_u64(i + 1))).unwrap();
            roots.push(t.root());
        }
        // 128 appends overwrite slot 0 (the empty root); the last 128 roots are known.
        assert_eq!(t.current_root_index, 0);
        assert!(!t.is_known_root(&empty));
        for r in &roots[1..] {
            assert!(t.is_known_root(r));
        }
        t.append_pair(&be(&from_u64(999)), &be(&from_u64(999))).unwrap();
        assert!(!t.is_known_root(&roots[1]));
        assert!(t.is_known_root(&roots[2]));
    }

    #[test]
    fn full_tree_rejected() {
        let mut t = empty_tree();
        t.next_index = CAPACITY - 2;
        assert!(t.append_pair(&[0u8; 32], &[0u8; 32]).is_ok());
        assert!(t.append_pair(&[0u8; 32], &[0u8; 32]).is_err());
        let mut t = empty_tree();
        t.next_index = 1;
        assert!(t.append_pair(&[0u8; 32], &[0u8; 32]).is_err());
    }

    #[test]
    fn non_canonical_leaf_rejected_by_poseidon() {
        let mut t = empty_tree();
        assert!(t.append_pair(&[0xff; 32], &[0u8; 32]).is_err());
    }
}
