//! Generate the cross-language test vectors (deterministic). Usage, from the
//! repo root: `cargo run -p polypus-crypto --bin gen-vectors`
//!
//! Writes:
//! - spec/vectors/*.json and spec/vectors/kernel/<scenario>.Prover.toml
//! - circuits/polypus_notes/src/vectors.nr (known-answer values for Noir tests)
//! - circuits/kernel/src/fixtures.nr (honest kernel witnesses for Noir tests)

use polypus_crypto::ext_data::ExtData;
use polypus_crypto::field::{tag, to_hex, Fr};
use polypus_crypto::hash::{poseidon, tags::ALL_TAGS};
use polypus_crypto::kernel::KernelWitness;
use polypus_crypto::keys::SpendingKey;
use polypus_crypto::merkle::{zeros, MerkleTree, DEPTH};
use polypus_crypto::note::{asset_id, nullifier, rcm, Note};
use polypus_crypto::scenarios::{standard_scenarios, TEST_MINT};
use serde_json::{json, Value};
use std::fmt::Write as _;
use std::path::Path;

fn h(x: &Fr) -> Value {
    Value::String(to_hex(x))
}

fn ext_json(e: &ExtData) -> Value {
    json!({
        "pool_id": hex::encode(e.pool_id), "chain_domain": hex::encode(e.chain_domain),
        "public_account": hex::encode(e.public_account), "relayer": hex::encode(e.relayer),
        "ext_amount": e.ext_amount, "fee": e.fee, "not_before_slot": e.not_before_slot,
        "ct_hash": [hex::encode(e.ct_hash[0]), hex::encode(e.ct_hash[1])],
        "bytes": hex::encode(e.bytes()), "ext_data_hash": h(&e.hash()),
        "public_amount": h(&e.public_amount()),
    })
}

fn noir_arr(xs: impl IntoIterator<Item = Fr>) -> String {
    format!("[{}]", xs.into_iter().map(|x| to_hex(&x)).collect::<Vec<_>>().join(", "))
}

fn noir_witness(w: &KernelWitness) -> String {
    let p = &w.public;
    let mut s = String::new();
    writeln!(s, "    Witness {{").unwrap();
    writeln!(s, "        pi_hash: {},", to_hex(&w.pi_hash)).unwrap();
    writeln!(s, "        public: PublicValues {{").unwrap();
    writeln!(s, "            root: {},", to_hex(&p.root)).unwrap();
    writeln!(s, "            nf: {},", noir_arr(p.nf)).unwrap();
    writeln!(s, "            cm_out: {},", noir_arr(p.cm_out)).unwrap();
    for (k, v) in [
        ("public_amount", p.public_amount),
        ("public_asset_id", p.public_asset_id),
        ("ext_data_hash", p.ext_data_hash),
        ("program_id", p.program_id),
        ("program_io_hash", p.program_io_hash),
    ] {
        writeln!(s, "            {k}: {},", to_hex(&v)).unwrap();
    }
    writeln!(s, "        }},").unwrap();
    writeln!(s, "        ask: {},\n        nk: {},\n        asset_id: {},", to_hex(&w.ask), to_hex(&w.nk), to_hex(&w.asset_id)).unwrap();
    writeln!(s, "        inputs: [").unwrap();
    for i in &w.inputs {
        writeln!(
            s,
            "            InputNote {{ amount: {}, d: {}, lock_program: {}, lock_data: {}, escape: {}, rseed: {}, leaf_index: {}, path: {} }},",
            to_hex(&i.amount), to_hex(&i.d), to_hex(&i.lock_program), to_hex(&i.lock_data),
            to_hex(&i.escape), to_hex(&i.rseed), to_hex(&i.leaf_index), noir_arr(i.path)
        )
        .unwrap();
    }
    writeln!(s, "        ],\n        outputs: [").unwrap();
    for o in &w.outputs {
        writeln!(
            s,
            "            OutputNote {{ amount: {}, owner: {}, lock_program: {}, lock_data: {}, escape: {}, rseed: {} }},",
            to_hex(&o.amount), to_hex(&o.owner), to_hex(&o.lock_program), to_hex(&o.lock_data),
            to_hex(&o.escape), to_hex(&o.rseed)
        )
        .unwrap();
    }
    writeln!(s, "        ],\n        program_params_hash: {},\n    }}", to_hex(&w.program_params_hash)).unwrap();
    s
}

const GENERATED: &str = "// @generated by `cargo run -p polypus-crypto --bin gen-vectors`. Do not edit.\n";

fn main() {
    let root = Path::new(".");
    let vdir = root.join("spec/vectors");
    std::fs::create_dir_all(vdir.join("kernel")).unwrap();

    // Poseidon KATs: inputs 1..=n for every arity usable on-chain.
    let poseidon_kat: Vec<(Vec<Fr>, Fr)> = (1..=12u64)
        .map(|n| {
            let ins: Vec<Fr> = (1..=n).map(Fr::from).collect();
            let out = poseidon(&ins);
            (ins, out)
        })
        .collect();

    // Keys.
    let keys_v: Vec<Value> = (1u8..=3)
        .map(|b| {
            let sk = SpendingKey::from_seed([b; 32]);
            let fvk = sk.full_viewing_key();
            let addrs: Vec<Value> = (0..2)
                .map(|j| {
                    let a = sk.address(j);
                    json!({ "index": j, "diversifier": hex::encode(a.d.0), "diversifier_field": h(&a.d.to_field()),
                            "pk_d": hex::encode(a.pk_d), "owner": h(&a.owner), "encoded": a.encode() })
                })
                .collect();
            json!({ "seed": hex::encode([b; 32]), "ask": h(&sk.ask()), "nk": h(&sk.nk()), "ak": h(&fvk.ak),
                    "ivk": hex::encode(fvk.ivk), "fvk_encoded": fvk.encode(),
                    "ivk_encoded": fvk.incoming().encode(), "addresses": addrs })
        })
        .collect();

    // Notes.
    let aid = asset_id(&TEST_MINT);
    let sk1 = SpendingKey::from_seed([1; 32]);
    let a1 = sk1.address(0);
    let kat_note = Note::plain(aid, 100, a1.owner, Fr::from(2u64));
    let kat_cm = kat_note.commitment();
    let kat_nf = nullifier(&sk1.nk(), &kat_cm, 5);
    let notes_v: Vec<Value> = [(0u64, 1u64), (100, 2), (u64::MAX, 3)]
        .iter()
        .map(|&(amount, rs)| {
            let n = Note::plain(aid, amount, a1.owner, Fr::from(rs));
            let cm = n.commitment();
            json!({ "asset_id": h(&n.asset_id), "amount": amount.to_string(), "owner": h(&n.owner),
                    "lock_program": h(&n.lock_program), "lock_data": h(&n.lock_data), "escape": h(&n.escape),
                    "rseed": h(&n.rseed), "rcm": h(&rcm(&n.rseed)), "commitment": h(&cm),
                    "nk": h(&sk1.nk()), "leaf_index": 5, "nullifier": h(&nullifier(&sk1.nk(), &cm, 5)) })
        })
        .collect();

    // Merkle: leaves 1..4.
    let mut t = MerkleTree::new();
    for i in 1..=4u64 {
        t.append(Fr::from(i)).unwrap();
    }
    let path2 = t.path(2).unwrap();

    let scenarios = standard_scenarios();

    let write = |name: &str, v: Value| {
        std::fs::write(vdir.join(name), serde_json::to_string_pretty(&v).unwrap() + "\n").unwrap();
    };
    write(
        "poseidon.json",
        json!({ "params": "circomlib BN254 x^5 (light-poseidon new_circom / sol_poseidon Bn254X5 BE / noir-lang/poseidon bn254::hash_n)",
                "vectors": poseidon_kat.iter().map(|(i, o)| json!({ "inputs": i.iter().map(h).collect::<Vec<_>>(), "output": h(o) })).collect::<Vec<_>>() }),
    );
    write("tags.json", json!(ALL_TAGS.iter().map(|(n, s)| json!({ "name": n, "string": s, "value": h(&tag(s)) })).collect::<Vec<_>>()));
    write("merkle.json", json!({ "depth": DEPTH, "zeros": zeros().iter().map(h).collect::<Vec<_>>(),
        "small_tree": { "leaves": ["1", "2", "3", "4"], "root": h(&t.root()), "path_leaf_2": path2.iter().map(h).collect::<Vec<_>>() } }));
    write("keys.json", json!(keys_v));
    write("notes.json", json!({ "mint": hex::encode(TEST_MINT), "asset_id": h(&aid), "notes": notes_v }));
    write("ext_data.json", json!(scenarios.iter().map(|s| json!({ "scenario": s.name, "ext": ext_json(&s.ext) })).collect::<Vec<_>>()));
    write(
        "kernel.json",
        json!(scenarios.iter().map(|s| { let w = &s.witness; json!({
            "scenario": s.name, "pi_hash": h(&w.pi_hash), "root": h(&w.public.root),
            "nf": w.public.nf.iter().map(h).collect::<Vec<_>>(), "cm_out": w.public.cm_out.iter().map(h).collect::<Vec<_>>(),
            "public_amount": h(&w.public.public_amount), "public_asset_id": h(&w.public.public_asset_id),
            "ext_data_hash": h(&w.public.ext_data_hash) }) }).collect::<Vec<_>>()),
    );
    for s in &scenarios {
        std::fs::write(vdir.join(format!("kernel/{}.Prover.toml", s.name)), s.witness.to_prover_toml()).unwrap();
    }

    // Noir: known-answer vectors for polypus_notes.
    let mut nv = String::from(GENERATED);
    writeln!(nv, "//! Known-answer values computed by the Rust reference (polypus-crypto).\n").unwrap();
    for (ins, out) in &poseidon_kat {
        writeln!(nv, "pub global POSEIDON_{}: Field = {};", ins.len(), to_hex(out)).unwrap();
    }
    for (n, s) in ALL_TAGS {
        writeln!(nv, "pub global {}: Field = {}; // {s}", n.to_uppercase(), to_hex(&tag(s))).unwrap();
    }
    let mint_hi = polypus_crypto::field::from_short_be(&TEST_MINT[..16]);
    let mint_lo = polypus_crypto::field::from_short_be(&TEST_MINT[16..]);
    for (k, v) in [
        ("MINT_HI", mint_hi),
        ("MINT_LO", mint_lo),
        ("ASSET_ID", aid),
        ("ASK", sk1.ask()),
        ("NK", sk1.nk()),
        ("AK", sk1.full_viewing_key().ak),
        ("D", a1.d.to_field()),
        ("OWNER", a1.owner),
        ("NOTE_AMOUNT", Fr::from(100u64)),
        ("NOTE_RSEED", Fr::from(2u64)),
        ("NOTE_CM", kat_cm),
        ("NOTE_NF_AT_5", kat_nf),
        ("SMALL_TREE_ROOT", t.root()),
        ("EMPTY_ROOT", zeros()[DEPTH]),
    ] {
        writeln!(nv, "pub global {k}: Field = {};", to_hex(&v)).unwrap();
    }
    writeln!(nv, "pub global SMALL_TREE_PATH_2: [Field; {DEPTH}] = {};", noir_arr(path2)).unwrap();
    std::fs::write(root.join("circuits/polypus_notes/src/vectors.nr"), nv).unwrap();

    // Noir: kernel fixtures.
    let mut fx = String::from(GENERATED);
    writeln!(fx, "//! Honest kernel witnesses for the standard scenario (polypus_crypto::scenarios).\n").unwrap();
    writeln!(fx, "use crate::kernel::{{InputNote, OutputNote, PublicValues, Witness}};\n").unwrap();
    for s in &scenarios {
        writeln!(fx, "pub fn {}() -> Witness {{\n{}}}\n", s.name, noir_witness(&s.witness)).unwrap();
    }
    std::fs::write(root.join("circuits/kernel/src/fixtures.nr"), fx).unwrap();

    eprintln!("wrote spec/vectors, circuits/polypus_notes/src/vectors.nr, circuits/kernel/src/fixtures.nr");
}
